export function getExamPapersByVersion(version: 'hsk2' | 'hsk3'): ExamPaperMetadata[] {
  return EXAM_PAPER_CATALOG.filter((p) => p.hskVersion === version);
}

export function getExamPapersByLevel(
  version: 'hsk2' | 'hsk3',
  level: number
): ExamPaperMetadata[] {
  if (version === 'hsk3' && (level === 7 || level === 8 || level === 9)) {
    // Return unified Advanced Band 7-9 paper
    return EXAM_PAPER_CATALOG.filter((p) => p.hskVersion === 'hsk3' && p.level === 7);
  }
  return EXAM_PAPER_CATALOG.filter((p) => p.hskVersion === version && p.level === level);
}

export function getExamPaperById(paperId: string): ExamPaperMetadata | undefined {
  return EXAM_PAPER_CATALOG.find((p) => p.paperId === paperId);
}
