export function getQuestionsByPaperId(paperId: string): ExamQuestion[] {
  return MASTER_EXAM_QUESTION_BANK.filter((q) => q.paperId === paperId);
}

export function getQuestionsByVersionAndLevel(
  version: 'hsk2' | 'hsk3',
  level: number
): ExamQuestion[] {
  if (version === 'hsk3' && (level === 7 || level === 8 || level === 9)) {
    return MASTER_EXAM_QUESTION_BANK.filter((q) => q.hskVersion === 'hsk3' && q.hskLevel === 7);
  }
  return MASTER_EXAM_QUESTION_BANK.filter(
    (q) => q.hskVersion === version && q.hskLevel === level
  );
}
